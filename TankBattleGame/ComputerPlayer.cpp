#include "ComputerPlayer.h"
constexpr int DISTANCE = 2;
constexpr int ZERO = 0;
constexpr int ONE = 1;
constexpr int TANK = 5;
constexpr int STEP = 25;


// Main decision-making function for computer player
bool ComputerPlayer::autoGenerateDirection(Player* name) {
	// Check if current tank is dead; if so, switch to another one
	if (thisTankDead(tankP)) {
		tankReplacement();
	}
	s[tankP].setStayTrack(false);
	int dist = DISTANCE;
	if (transition > ZERO) {
		tankReplacement();
		transition--;
		return true;
	}
	else if (saveMove) {
		saveMove = false;
		
		s[tankP].setAddDir(s[tankP].forward());
		s[tankP].setStayTrack(false);
		return false;;
	}
	else if (shellThreatNearby(&s[tankP], name, dist)){
		s[tankP].setAddDir(s[tankP].Right45degrees());
		s[tankP].setStayTrack(false);
		saveMove = true;
		return false;
	}
	else {
		
		int attempts = ONE;
		int temp = (tankP+ONE) % numTanks;
		while (attempts < numTanks) {
			if (!thisTankDead(temp)) {
				if (shellThreatNearby(&s[temp], name, dist + attempts)) {
					tankReplacement();
					transition = attempts-1;
					return true;
				}
			}
			attempts++;
			temp = (temp + ONE) % numTanks;

		}
	}
	// Check if the tank can shoot the enemy
	if (s[tankP].getCanonExist() && canShoot(name)) {
		if (s[tankP].getNumShells() == ZERO) {
			s[tankP].setShot(true);
			s[tankP].setStayTrack(true);
		}
		//s[tankP].setAddDir(s[tankP].forward());
		return false;
	}
	// Otherwise, move randomly
	if (randomMove(&s[tankP]))
		return true;
	return false;
	
}
// Replaces the current tank with the next available alive tank
void ComputerPlayer::tankReplacement() {
	//tankP = (tankP + 1) % numTanks;
	//int oldTank = tankP;
	int attempts = ZERO;
		do {
			tankP = (tankP + ONE) % numTanks; // Moving to the next tank
			attempts++;

		} while (thisTankDead(tankP) && attempts < numTanks);
		s[tankP].setStayTrack(false);
}
// Picks a random direction to move or replace the tank
bool ComputerPlayer::randomMove(Tank* tank) {
	if (!tank || tank->getLostLife())
		return false;
	// // Create a number generator
	std::random_device rd;
	std::mt19937 gen(rd());
	std::uniform_int_distribution<> dist(0, 99);

	int num = dist(gen);  // This is the drawn number

	if (num < 65) {
		s[tankP].setAddDir(tank->forward());
		s[tankP].setStayTrack(false);
	}
	else if (num < 70){
		s[tankP].setAddDir(tank->Backward());
		s[tankP].setStayTrack(false);
	}
	else if (num < 75){
		s[tankP].setAddDir(tank->Right45degrees());
		s[tankP].setStayTrack(false);
	}
	else if (num < 80) {
		s[tankP].setAddDir(tank->Left45degrees());
		s[tankP].setStayTrack(false);
	}
	else if (num < 85) {
		tank->setAddDir(tank->Right90degrees());
		s[tankP].setStayTrack(false);
	}
	else if (num < 90) {
		s[tankP].setAddDir(tank->Left90degrees());
		s[tankP].setStayTrack(false);
	}
	else if (num < 95) {
		s[tankP].setAddDir(tank->StayTank());
	}
	else {
		tankReplacement();
		return true;
	}
	return false;
}
// Detects if any shell (enemy or own) is dangerously close to the given tank
bool ComputerPlayer::shellThreatNearby(Tank* tank, Player* name, int distance) {
	// Check enemy shells
	for (int i = 0; i < name->getNumTank(); i++) {
		for (int s = 0; s < TANK; s++) {
			if (name->getTank(i).getShell(s).isActive()) {
				Point tempT = tank->getPos();
				Point tempS = name->getTank(i).getShell(s).getPos();
				int dx = abs(tempT.getX() - tempS.getX());
				int dy = abs(tempT.getY() - tempS.getY());
				if (dx <= distance && dy <= distance) {
					// There is a threat – the shell is close
					for (int j = 0; j < distance; j++) {
						tempT.move(tank->getDir());
						tempS.move(name->getTank(i).getShell(s).getDirection());
						if (tempT == tempS) {
							return true;
						}
					}
				}
			}
		}
	}
	// Check own shells
	for (int i = 0; i < this->getNumTank(); i++) {
		for (int s = 0; s < TANK; s++) {
			if (getTank(i).getShell(s).isActive()) {
				Point tempT = tank->getPos();
				Point tempS = getTank(i).getShell(s).getPos();
				int dx = abs(tempT.getX() - tempS.getX());
				int dy = abs(tempT.getY() - tempS.getY());
				if (dx <= distance && dy <= distance) {
					// There is a threat – the shell is close
					for (int j = 0; j < distance; j++) {
						tempT.move(tank->getDir());
						tempS.move(getTank(i).getShell(s).getDirection());
						if (tempT == tempS) {
							return true;
						}
					}
				}
			}
		}
	}

	return false;

}
// Checks if current tank can shoot enemy without hitting friendly units
bool ComputerPlayer::canShoot(Player* name) {
	Point tempT = s[tankP].getPos();
	Point tempC = s[tankP].getCanon();
	int direction = s[tankP].getDir();
	bool opponent = false;
	bool myTank = false;
	tempC.move(direction);
	for (int step = 0; step < STEP; ++step) {
		tempC.move(direction);
		for (int i = 0; i < name->getNumTank(); i++) {
			if (!(name->getTank(i).getLostLife())&& !opponent) {
				if (tempC == name->getTank(i).getPos() || (tempC == name->getTank(i).getCanon() && name->getTank(i).getCanonExist())) {
					opponent = true;

				}
			}
		}
		for (int j = 0; j < getNumTank(); j++) {
			if (!getTank(j).getLostLife() && !myTank && j != tankP) {
				if (tempC == getTank(j).getPos() || (tempC == getTank(j).getCanon() && getTank(j).getCanonExist())) {
					myTank = true;
				}
			}
		}
		if (opponent) {
			return true;
		}
		else if (myTank) {
			return false;
		}
	}
	return false;
}