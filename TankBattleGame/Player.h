#pragma once
#include <random>

#include "Tank.h"
#include "Board.h"
#include "Point.h"
#include "Utils.h"

constexpr int TANK_NUM = 5;

class Player
{
    private:
                // Tanks for the player
      Board* board = nullptr;       // Player board
      bool isSilent = false;
      int Points = 0;               // Points in the game per player
      bool lost=false;              // Player lost
      //bool isComputer = false;
    protected:
      Tank s[TANK_NUM];   
      int numTanks = 0;             // Number of tanks
      int tankP = 0;
    public:
        //Tank boot functions
        void initTanksFromPositions(const std::vector<Point>& positions, const char* keys, Colors color, Board& b); //Player Tank Boot
        void tankBooleanReset();                    //Reset variables of all tanks
        void setAllTank();                          //Updated movement direction for tanks
        
       
        //Displacement functions and their effects
        void moveAllTank(Player& name);             //Moving all tanks in the game
        bool tankClash(Player& name, int tank);     //Tank clash
        bool allTanksDead();                        // Checking if all of a player's tanks are dead
        bool thisTankDead(int num);                 // Checking a specific tank's thickness if it is dead

        void setTankBoard(Board& b);                // Places tanks on the board
        void addPoints(int add);                    //Adds points to the player

        //Functions returning variables
        int getPoints () const { return Points; }         //Player's point return
        int getNumTank() const { return numTanks; }        //Number of tanks return
        bool getLost() const { return lost; }             //Returns, did you lose?
        Tank& getTank(int num)  { return s[num]; }        // Tank return
        int getTankP() { return tankP; }
        void setNumTank(int num) { numTanks=num; }

        virtual void setTankP(int num) { tankP = num; }         // Updates tank number
        virtual bool isComputerPlayer() const { return false; } // Checks variable
        virtual bool autoGenerateDirection(Player* name) { return false; }; // Auto player
};

